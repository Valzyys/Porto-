export type IconName = keyof typeof ICONS;

type Props = {
  name: IconName;
  /** ukuran sisi dalam px CSS */
  size?: number;
  className?: string;
  /** label untuk screen reader; tanpa label → dekoratif */
  label?: string;
};

export function PixelIcon({ name, size = 18, className, label }: Props) {
  const rows = ICONS[name];
  const rects: React.ReactNode[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === "#") rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" />);
    }
  });
  return (
    <svg
      viewBox="0 0 9 9"
      width={size}
      height={size}
      fill="currentColor"
      shapeRendering="crispEdges"
      className={className}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      {rects}
    </svg>
  );
}
